/** Prefer explicit updatedAtMls, else newest history stamp, else listedAt. */
function resolveUpdatedAtMls(listing: SeedListing): Date {
  if (listing.updatedAtMls) return new Date(listing.updatedAtMls);
  let latest: number | null = null;
  for (const h of listing.history ?? []) {
    const stamp = h.lastUpdatedAt ?? h.contractDate;
    const t = new Date(stamp).getTime();
    if (Number.isFinite(t) && (latest == null || t > latest)) latest = t;
  }
  if (latest != null) return new Date(latest);
  return new Date(listing.listedAt);
}

export function toListingCreateInput(
  listing: SeedListing,
  options?: { ownerUserId?: string },
): Prisma.ListingCreateInput {
  const isFsbo = listing.dataSource === "fsbo";
  return {
    mlsNumber: listing.mlsNumber,
    status: listing.status,
    segment: listing.segment ?? "RESIDENTIAL",
    transactionType: listing.transactionType ?? "SALE",
    dataSource: listing.dataSource ?? "mock",
    propertyType: listing.propertyType,
    listPrice: listing.listPrice,
    soldPrice: listing.soldPrice,
    beds: listing.beds,
    baths: listing.baths,
    sqft: listing.sqft,
    parkingSpaces: listing.parkingSpaces ?? 0,
    yearBuilt: listing.yearBuilt,
    taxes: listing.taxes,
    maintenanceFee: listing.maintenanceFee,
    addressLine: listing.addressLine,
    unitNumber: listing.unitNumber,
    city: listing.city,
    community: listing.community,
    postalCode: listing.postalCode,
    lat: listing.lat,
    lng: listing.lng,
    description: listing.description,
    brokerageName: listing.brokerageName,
    listedAt: new Date(listing.listedAt),
    soldAt: listing.soldAt ? new Date(listing.soldAt) : null,
    updatedAtMls: resolveUpdatedAtMls(listing),
    daysOnMarket: listing.daysOnMarket,
    isMock: true,
    ownerStatus: listing.ownerStatus ?? null,
    owner:
      listing.assignDemoOwner && options?.ownerUserId
        ? { connect: { id: options.ownerUserId } }
        : undefined,
    ownerReviewedAt: isFsbo && listing.ownerStatus === "ACTIVE" ? new Date() : null,
    media: {
      create: listing.images.map((url, index) => ({
        url,
        sortOrder: index,
        isPrimary: index === 0,
      })),
    },
    openHouses: listing.openHouses
      ? {
          create: listing.openHouses.map((oh) => ({
            startsAt: new Date(oh.startsAt),
            endsAt: new Date(oh.endsAt),
            notes: oh.notes,
          })),
        }
      : undefined,
    history: listing.history
      ? {
          create: listing.history.map((h) => ({
            event: h.event,
            price: h.price,
            originalPrice: h.originalPrice ?? null,
            contractDate: new Date(h.contractDate),
            lastUpdatedAt: h.lastUpdatedAt ? new Date(h.lastUpdatedAt) : null,
            externalMls: h.externalMls,
            visibility: h.visibility ?? "restricted",
            note: h.note,
          })),
        }
      : undefined,
  };
}
