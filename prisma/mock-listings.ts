/** Build an 8-photo gallery, keeping any preferred cover shots first. */
function gallery(seed: number, preferred: string[] = []): string[] {
  const out = [...preferred];
  for (let i = 0; out.length < 8; i += 1) {
    const next = IMG[(seed * 3 + i * 2) % IMG.length]!;
    if (!out.includes(next)) out.push(next);
    else out.push(IMG[(seed + i) % IMG.length]!);
  }
  return out.slice(0, 8);
}

function upcomingSaturday(hour: number, daysAhead = 0) {
  const d = new Date();
  const day = d.getDay();
  const toSat = ((6 - day + 7) % 7) + daysAhead * 7;
  d.setDate(d.getDate() + (toSat === 0 ? 7 : toSat));
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
}

